-- Ejecutar como el usuario propietario "postgres" dentro de cabana_porcina_db.

GRANT CONNECT ON DATABASE cabana_porcina_db TO cabana_dev;
GRANT USAGE ON SCHEMA operacional, dw TO cabana_dev;

GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA operacional, dw
TO cabana_dev;

GRANT USAGE, SELECT
ON ALL SEQUENCES IN SCHEMA operacional, dw
TO cabana_dev;

GRANT EXECUTE
ON ALL ROUTINES IN SCHEMA operacional, dw
TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA operacional
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA dw
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA operacional
GRANT USAGE, SELECT ON SEQUENCES TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA dw
GRANT USAGE, SELECT ON SEQUENCES TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA operacional
GRANT EXECUTE ON ROUTINES TO cabana_dev;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA dw
GRANT EXECUTE ON ROUTINES TO cabana_dev;
